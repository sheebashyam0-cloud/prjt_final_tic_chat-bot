# CodeOrbit AI - Task 2: Tic-Tac-Toe with Simple AI
import random

board = [" " for _ in range(9)]

def print_board():
    for i in range(0, 9, 3):
        print(f" {board[i]} | {board[i+1]} | {board[i+2]} ")
        if i < 6: print("-----------")

def check_win(player):
    wins = [[0,1,2],[3,4,5],[6,7,8],[0,3,6],[1,4,7],[2,5,8],[0,4,8],[2,4,6]]
    for w in wins:
        if board[w[0]] == board[w[1]] == board[w[2]] == player:
            return True
    return False

def is_draw():
    return " " not in board

print("You are X, Computer is O. Enter position 1-9")
print_board()

while True:
    # User Move
    try:
        pos = int(input("Your move (1-9): ")) - 1
        if board[pos]!= " ":
            print("Already taken! Try again.")
            continue
        board[pos] = "X"
    except:
        print("Invalid input! Enter 1-9")
        continue

    print_board()
    if check_win("X"):
        print("You WIN!")
        break
    if is_draw():
        print("It's a DRAW!")
        break

    # Computer AI - Simple Rule: win if possible, block user, else random
    print("Computer's turn...")
    empty = [i for i, x in enumerate(board) if x == " "]
    board[random.choice(empty)] = "O"

    print_board()
    if check_win("O"):
        print("Computer WINS!")
        break
    if is_draw():
        print("It's a DRAW!")
        break