# CodeOrbit AI - Task 1: Rule-Based Chatbot

def chatbot_response(user_input):
    user_input = user_input.lower()

    # Greeting rules
    if "hello" in user_input or "hi" in user_input:
        return "Hello! I am CodeOrbit Bot. How can I help you?"
    elif "how are you" in user_input:
        return "I am fine, thank you! What about you?"
    elif "your name" in user_input:
        return "I am a simple rule-based chatbot created for CodeOrbit Tech internship."
    elif "help" in user_input:
        return "I can answer greetings, tell you about AI, and chat. Try asking 'what is AI?'"
    elif "what is ai" in user_input:
        return "AI is Artificial Intelligence - machines that can think like humans."
    elif "bye" in user_input or "exit" in user_input:
        return "Goodbye! Thanks for chatting. Bye!"
    else:
        # Fallback for unknown input
        return "Sorry, I didn't understand that. Can you rephrase?"

print("--- CodeOrbit Chatbot (Type 'bye' to exit) ---")
while True:
    user = input("You: ")
    response = chatbot_response(user)
    print(f"Bot: {response}")
    if "bye" in user.lower():
        break